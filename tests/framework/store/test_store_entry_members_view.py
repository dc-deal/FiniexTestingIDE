"""
The entry members view (#621): the table `store_cli.py entry-members` prints, and the Markdown form
the architecture document carries — held to the declaration so the document cannot fall behind it.
"""

import re
from pathlib import Path

import pytest

from python.framework.reporting.console.store_entry_members_summary import (
    MOMENT_LABELS,
    entry_members_markdown,
    render_entry_members,
)
from python.framework.store.entry_members.run_entry_members import RUN_ENTRY_MEMBERS
from python.framework.store.entry_members.sweep_entry_members import SWEEP_ENTRY_MEMBERS
from python.framework.store.store_catalog import StoreCatalog
from python.framework.types.store_member_types import EntryMemberMoment
from python.framework.types.store_types import StoreId
from tests.shared.markdown_anchor_helpers import heading_anchors

_PROJECT_ROOT = Path(__file__).resolve().parents[3]
_DOC = _PROJECT_ROOT / 'docs/architecture/store_entry_members.md'
_MEMBERS = {'runs': RUN_ENTRY_MEMBERS, 'sweeps': SWEEP_ENTRY_MEMBERS}


def _generated_table(store: str) -> str:
    """
    The table the document carries for one store, between its markers.

    Args:
        store: The store id the table was generated for

    Returns:
        The table's lines, without the markers
    """
    text = _DOC.read_text(encoding='utf-8')
    start = f'<!-- generated by: store_cli.py entry-members {store} --markdown -->\n'
    assert start in text, f'the document has no generated table for {store}'
    body = text.split(start, 1)[1]
    return body.split('\n<!-- end of generated table -->', 1)[0]


class TestTheDocumentCarriesTheDeclaration:
    """Regenerate with `store_cli.py entry-members <store> --markdown` when one of these fails."""

    @pytest.mark.parametrize('store', sorted(_MEMBERS))
    def test_the_table_is_the_one_the_declaration_produces(self, store):
        assert _generated_table(store) == entry_members_markdown(_MEMBERS[store]), (
            f'the {store} table in {_DOC.name} is out of date — paste the output of '
            f'store_cli.py entry-members {store} --markdown between its markers')

    @pytest.mark.parametrize('store', sorted(_MEMBERS))
    def test_every_link_in_the_table_reaches_a_heading(self, store):
        links = re.findall(r'\]\(([^)]+)\)', entry_members_markdown(_MEMBERS[store]))
        assert links
        for link in links:
            path, _, anchor = link.partition('#')
            target = (_DOC.parent / path).resolve()
            assert target.is_file(), link
            assert anchor in heading_anchors(target), link


class TestTheConsoleView:
    """What `store_cli.py entry-members` prints."""

    def test_every_moment_has_a_label(self):
        assert set(MOMENT_LABELS) == set(EntryMemberMoment)

    def test_every_member_is_listed(self, capsys):
        render_entry_members(StoreCatalog().get(StoreId.RUNS))
        printed = capsys.readouterr().out
        for member in RUN_ENTRY_MEMBERS:
            assert member.member_id.value in printed, member.member_id

    def test_a_store_of_single_files_says_so(self, capsys):
        render_entry_members(StoreCatalog().get(StoreId.RUN_LEDGER))
        assert 'one entry is a single file' in capsys.readouterr().out
