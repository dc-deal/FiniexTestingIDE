    @staticmethod
    def _fees_charged(jsonl_path: str, events: List[Dict[str, Any]]) -> Dict[str, Any]:
        """
        What the run booked in fees, read from the run's own report (#566).

        The report beside the capture carries `fees_charged` — every fee the run booked, open
        positions included. Where that report is gone, no longer reads, or names no single
        currency, the capture's fill lines carry each execution's fee and add up to the same
        bookings; the source says which was read. Neither can show a fee we computed wrong — both
        are our booking. The control is `account_delta`; whose figure each fill's fee is, the
        venue's or our estimate, says `fee_source`.

        Args:
            jsonl_path: The capture, in its run directory
            events: The capture's lines

        Returns:
            {'value', 'currency', 'source'} — source 'run_record', 'event_sum' or 'not_available'
        """
        charged = []
        try:
            summary = RunDirReader(Path(jsonl_path).parent).read_section(RUN_SUMMARY_ARTIFACT)
            if summary is not None:
                charged = [row for row in summary.currencies if row.fees_charged is not None]
        except ValueError:
            # A report written by another version of its model no longer validates — the
            # capture's own lines still add up to the same bookings.
            charged = []
        if len(charged) == 1:
            return {'value': charged[0].fees_charged, 'currency': charged[0].currency,
                    'source': 'run_record'}
        fills = [(e.get('extra') or {}) for e in events if e.get('event_type') in _FILL_LINES]
        fees = [fill['fee'] for fill in fills if fill.get('fee') is not None]
        if not fees:
            return {'value': None, 'currency': None, 'source': 'not_available'}
        currency = next((fill['fee_currency'] for fill in fills if fill.get('fee_currency')), None)
        return {'value': sum(fees), 'currency': currency, 'source': 'event_sum'}

    @staticmethod
    def _fee_source(header: Dict[str, Any], events: List[Dict[str, Any]]) -> Dict[str, Any]:
        """
        Whose figure each fill's fee is — the venue's own, or our fee model's estimate (#508).

        Counted over the capture's fill lines, beside what the venue declared about where it
        reports a fill's fee. A fill line without a source counts as `not_recorded` — every line
        of a capture from before the source was recorded, so such a capture reads `not_recorded`
        as a whole: a missing measurement, never a failure, and never the venue's figure.

        Args:
            header: The capture's header
            events: The capture's lines

        Returns:
            {'status', 'fills', 'by_source', 'not_recorded', 'fee_report', 'venue_fee_expected'}
            — status 'recorded', 'partly_recorded', 'not_recorded' or 'no_fills'; `by_source`
            names every source, at zero too; `fee_report` and `venue_fee_expected` are None
            where the header does not record them
        """
        by_source: Dict[str, int] = {source.value: 0 for source in FeeSource}
        fills = 0
        not_recorded = 0
        for event in events:
            if event.get('event_type') not in _FILL_LINES:
                continue
            fills += 1
            source = (event.get('extra') or {}).get('fee_source')
            if source is None:
                not_recorded += 1
            else:
                by_source[source] = by_source.get(source, 0) + 1

        if fills == 0:
            status = 'no_fills'
        elif not_recorded == fills:
            status = 'not_recorded'
        elif not_recorded:
            status = 'partly_recorded'
        else:
            status = 'recorded'
        return {
            'status': status,
            'fills': fills,
            'by_source': by_source,
            'not_recorded': not_recorded,
            'fee_report': header.get('fee_report'),
            'venue_fee_expected': header.get('venue_fee_expected'),
        }

    @staticmethod
    def _fee_source_warnings(fee_source: Dict[str, Any]) -> List[str]:
        """
        Fills booked from the estimate where the venue should have stated the fee (#508).

        Said only where the session's executor expected the venue's fee — the venue reports it
        in the answer that reports the fill, and the session read a real account: there an
        estimate means that answer came without one, and the session's log names the order. A
        warning, never a failure — the run traded, one of its figures is ours rather than the
        venue's. The expectation is the executor's own answer, stamped into the capture's
        header, so the certificate and the session's warning cannot disagree about a dry run or
        a venue that reports no fee there. Where the capture does not record it, nothing can be
        judged.

        Args:
            fee_source: The certificate's fee-source block

        Returns:
            The warning, or an empty list
        """
        estimated = fee_source['by_source'].get(FeeSource.ESTIMATE.value, 0)
        if fee_source['venue_fee_expected'] is not True or not estimated:
            return []
        return [
            f"ESTIMATED FEES: {estimated} of {fee_source['fills']} fills booked from the fee "
            f"model's estimate, although this venue reports the fee in the answer that reports a "
            f'fill (fee_report {FeeReport.STATUS_ANSWER.value}). Those fees are ours, not what the '
            f'account was charged; the session log names each order, and the venue has its own '
            f'figure in its execution records.'
        ]

    @staticmethod
    def _run_checks(run_header: Optional[RunHeader]) -> Dict[str, Dict[str, Any]]:
        """
        What the run itself has to be for its capture to certify a release: a run whose orders
        went to the venue, from committed code — the same two things the security study holds
        each of its stages to.

        Args:
            run_header: The header of the run the capture lies in; None when it lies in no run
                directory, which proves neither

        Returns:
            Check name → whether it passed and why
        """
        if run_header is None:
            unproven = 'the capture lies in no run directory, so no header says'
            return {'study:real_orders': {'passed': False, 'detail': f'{unproven} where its '
                                                                     f'orders went'},
                    'study:committed_code': {'passed': False, 'detail': f'{unproven} which code '
                                                                        f'ran'}}
        real = run_header.orders_to is OrdersTo.VENUE
        orders_to = run_header.orders_to.value if run_header.orders_to else 'nowhere recorded'
        committed = (run_header.code_identity is not None
                     and not run_header.code_identity.is_dirty())
        return {
            'study:real_orders': {
                'passed': real,
                'detail': ('the run sent its orders to the venue' if real
                           else f'the run sent its orders to {orders_to}, not to the venue')},
            'study:committed_code': {
                'passed': committed,
                'detail': ('the run ran from committed code' if committed
                           else 'the run ran from uncommitted or unreadable code')},
        }

    @staticmethod
    def _run_directory(run_dir: Path) -> Dict[str, Any]:
        """
        The run directory the capture lies in, held to the run store's declaration — said in the
        certificate, never failed on.

        Args:
            run_dir: The capture's directory

        Returns:
            Whether it was checked, how the run closed, the files nobody declared and the members
            that need a look
        """
        if not is_run_directory(run_dir):
            return {'checked': False, 'reason': 'the capture does not lie in a run directory'}
        try:
            assessment = assess(run_dir)
        except (OSError, ValueError, KeyError) as error:
            return {'checked': False, 'reason': f"the run's header cannot be read ({error})"}
        return {
            'checked': True,
            'close_state': assessment.close_state.value,
            'undeclared': assessment.undeclared,
            'needs_a_look': [f'{member.member_id.value}: {member.state.value} — {member.reason}'
                             for member in assessment.members if member.state.needs_a_look()],
        }

    @staticmethod
    def _run_directory_warnings(run_directory: Dict[str, Any]) -> List[str]:
        """
        What the run directory check found, as warnings.

        Args:
            run_directory: The check's result

        Returns:
            One line per finding; empty when the run directory is as declared
        """
        if not run_directory.get('checked'):
            return []
        warnings = []
        close_state = RunCloseState(run_directory['close_state'])
        if close_state is not RunCloseState.CLOSED:
            warnings.append(f'The run is not closed ({CLOSE_LABELS[close_state]}): its record may '
                            f'be incomplete.')
        if run_directory['undeclared']:
            warnings.append(f"The run directory holds files the run store does not declare: "
                            f"{', '.join(run_directory['undeclared'])}.")
        for line in run_directory['needs_a_look']:
            warnings.append(f'A file of the run needs a look — {line}.')
        return warnings

    @staticmethod
    def _capture_warnings(cut_last_line: bool) -> List[str]:
        """
        What reading the capture found, as warnings.

        Args:
            cut_last_line: Whether the capture's last line was cut off

        Returns:
            One line when it was; empty otherwise
        """
        if not cut_last_line:
            return []
        return ["The capture's last line was cut off — the session stopped while writing it; "
                'the lines before it are read.']

    @staticmethod
    def _slippage(events: List[Dict[str, Any]]) -> Dict[str, Any]:
        """
        Each fill against what it is measured by, per order type (#566).

        Positive is adverse. A market order is measured against the mid when it was submitted —
        the #340 measurement — a limit against its own limit, never the mid, and a stop against its
        trigger, because a triggered stop fills at the market. A fill whose reference was not
        captured counts as a leg and not as measured; a capture from before the projection carries
        no source at all and reads `not_measured`, never 0.0.

        Args:
            events: The capture's lines

        Returns:
            The slippage block: per order type what it is measured against, its legs and figures,
            the sign, and a status
        """
        legs: Dict[str, List[Optional[float]]] = {}
        measured_against: Dict[str, str] = {}
        for event in events:
            if event.get('event_type') not in _FILL_LINES:
                continue
            source = event.get('slippage') or {}
            order_type = source.get('order_type')
            if order_type is None:
                continue
            measured_against.setdefault(order_type, source.get('measured_against', 'unknown'))
            side = source.get('side')
            pct = None
            if event.get('price') is not None:
                _, pct = adverse_slippage(
                    event['price'], source.get('reference_price'),
                    OrderSide(side) if side else None)
            legs.setdefault(order_type, []).append(pct)

        by_order_type: Dict[str, Dict[str, Any]] = {}
        for order_type, values in sorted(legs.items()):
            measured = [value for value in values if value is not None]
            block: Dict[str, Any] = {'legs': len(values), 'measured': len(measured)}
            if measured and order_type == 'limit':
                block['vs_limit_max_pct'] = max(measured)
            elif measured:
                block['adverse_avg_pct'] = sum(measured) / len(measured)
                block['adverse_max_pct'] = max(measured)
            by_order_type[order_type] = block

        total = sum(block['legs'] for block in by_order_type.values())
        measured_total = sum(block['measured'] for block in by_order_type.values())
        if measured_total == 0:
            status = 'not_measured'
        elif measured_total < total:
            status = 'partly_measured'
        else:
            status = 'measured'
        return {
            'measured_against': {order_type: measured_against[order_type]
                                 for order_type in by_order_type},
            'sign': 'positive = adverse',
            'by_order_type': by_order_type,
            'status': status,
        }

    @staticmethod
    def _api_calls(events: List[Dict[str, Any]]) -> Dict[str, Any]:
        """
        The session's broker REST calls, from the telemetry written at its end (#351).

        Args:
            events: The capture's lines

        Returns:
            {'status': 'recorded', 'calls', 'errors', 'slow_calls'}, or {'status': 'not_recorded'}
        """
        line = next(
            (e for e in reversed(events) if e.get('event_type') == CaptureLineType.API_PERF),
            None)
        if line is None:
            return {'status': 'not_recorded'}
        block = line.get('api_perf') or {}
        return {
            'status': 'recorded',
            'calls': sum(endpoint.get('calls', 0) for endpoint in block.get('endpoints', [])),
            'errors': block.get('errors', 0),
            'slow_calls': block.get('slow_calls', 0),
        }

    @staticmethod
    def _reconciliation(events: List[Dict[str, Any]]) -> Dict[str, Any]:
        """
        Whether the session reconciled against the venue, and what that found (#566).

        The capture's `reconcile_alert` lines are written only when the picture CHANGED, and at
        most one per minimum interval, so their count alone cannot tell a clean session from one
        that never compared or skipped every cycle. The session's own totals, written at its end,
        can.

        Args:
            events: The capture's lines

        Returns:
            {'status': 'checked' | 'partly_skipped' | 'skipped' | 'not_run' | 'disabled' |
            'not_recorded', ...} with the cycles, skipped cycles and divergences seen where
            recorded, and the divergent pictures the capture holds
        """
        divergent_records = sum(
            1 for e in events
            if e.get('event_type') == CaptureLineType.RECONCILE_ALERT
            and e.get('status') == ReconcileState.DIVERGENT.value)
        line = next(
            (e for e in reversed(events)
             if e.get('event_type') == CaptureLineType.RECONCILE_SUMMARY),
            None)
        if line is None:
            return {'status': 'not_recorded', 'divergent_records': divergent_records}
        summary = line.get('reconcile') or {}
        if not summary.get('enabled'):
            return {'status': 'disabled'}
        cycles = summary.get('cycles', 0)
        skipped = summary.get('skipped', 0)
        if cycles == 0:
            status = 'not_run'
        elif skipped >= cycles:
            status = 'skipped'
        elif skipped:
            status = 'partly_skipped'
        else:
            status = 'checked'
        return {
            'status': status,
            'cycles': cycles,
            'skipped': skipped,
            'divergences_seen': summary.get('divergences_seen', 0),
            'divergent_records': divergent_records,
        }

    @staticmethod
    def _account_delta(
        broker_snapshots: List[Dict[str, Any]],
        end_snapshot: Optional[Dict[str, Any]],
    ) -> Dict[str, Any]:
        """
        What the ACCOUNT moved between the first snapshot and the session-end one (#506).

        The venue-side counterpart to `fees_charged`: one figure is our booking, the other is
        the account, and their DIFFERENCE is how well we model the venue — which is the
        question the certificate exists to answer. It is a MEASUREMENT, never a gate: a cost
        the run cannot explain must be visible, not fatal.

        `status` is part of the answer rather than an afterthought. An absent or unreadable
        snapshot has to say so, because a silent empty delta reads as "nothing moved" — the
        exact failure a cost figure of zero already had.

        Args:
            broker_snapshots: Every broker-truth snapshot of the run, in order
            end_snapshot: The session-end snapshot, or None when it was never written

        Returns:
            {'status': ..., 'per_asset': {asset: delta}} — `per_asset` empty unless 'ok'
        """
        if not broker_snapshots or end_snapshot is None:
            return {'status': 'no_end_snapshot', 'per_asset': {}}
        if broker_snapshots[0] is end_snapshot:
            return {'status': 'single_snapshot', 'per_asset': {}}

        start_balances = (broker_snapshots[0].get('extra') or {}).get('balances')
        end_balances = (end_snapshot.get('extra') or {}).get('balances')
        if start_balances is None or end_balances is None:
            return {'status': 'balances_unreadable', 'per_asset': {}}

        # An asset listed on one side only appeared or vanished — that is a movement from or
        # to zero, not a reason to drop it.
        per_asset = {}
        for asset in sorted(set(start_balances) | set(end_balances)):
            moved = float(end_balances.get(asset, 0.0) or 0.0) - float(
                start_balances.get(asset, 0.0) or 0.0)
            if moved:
                per_asset[asset] = moved
        return {'status': 'ok', 'per_asset': per_asset}

    @staticmethod
    def _print_summary(out_path: Path, cert: Dict[str, Any]) -> None:
        """Print a concise operator-facing certificate summary."""
        status = cert['overall_status']
        mark = '✅' if status == 'PASSED' else '❌'
        print(f"\n{'=' * 60}")
        print(f'  {mark} FIELD STUDY CERTIFICATE — {status}')
        print(f"  release: {cert['release_version']}  |  commit: {cert['git_commit']}")
        print(f"  profile: {cert['profile']}  |  symbol: {cert['symbol']}")
        print(f"  phases: {cert['phase_count']}  |  flat at end: {cert['flat_at_session_end']}")
        if cert['failed_phases']:
            print(f"  failed:  {cert['failed_phases']}")
        if cert['missing_phases']:
            print(f"  missing: {cert['missing_phases']}")
        for name in cert.get('failed_checks') or []:
            print(f"  failed:  {name} — {cert['checks'][name]['detail']}")
        # The source is printed beside the figure: a total read from the run's report and one
        # added up from the capture are the same bookings, but only the first is the run's own.
        # Whose figure the fills' fees are follows it.
        fees = cert.get('fees_charged') or {}
        sources = FieldStudyCertificate._fee_source_text(cert.get('fee_source') or {})
        if fees.get('value') is None:
            print(f'  fees charged: not available{sources}')
        else:
            print(f"  fees charged: {fees['value']:.6f} {fees.get('currency') or ''} "
                  f"({fees.get('source')}){sources}")
        # The account's own movement beside our booking — a missing measurement is printed
        # as such rather than as a silent absence.
        delta = cert.get('account_delta') or {}
        if delta.get('status') == 'ok':
            moved = '  '.join(
                f'{asset} {amount:+.8f}' for asset, amount in delta['per_asset'].items())
            print(f"  account delta: {moved or 'nothing moved'}")
        else:
            print(f"  account delta: {delta.get('status', 'unknown')}")
        slippage = cert.get('slippage') or {}
        parts = []
        for order_type, block in (slippage.get('by_order_type') or {}).items():
            if 'vs_limit_max_pct' in block:
                parts.append(f"{order_type} max {block['vs_limit_max_pct']:+.4f}% vs limit "
                             f"({block['measured']}/{block['legs']})")
            elif 'adverse_max_pct' in block:
                parts.append(f"{order_type} avg {block['adverse_avg_pct']:+.4f}% "
                             f"max {block['adverse_max_pct']:+.4f}% "
                             f"({block['measured']}/{block['legs']})")
            else:
                parts.append(f"{order_type} not measured ({block['legs']} legs)")
        print(f"  slippage: {slippage.get('status', 'not_measured')}"
              + (f" — {' · '.join(parts)}" if parts else ''))
        reconciliation = cert.get('reconciliation') or {}
        if 'cycles' in reconciliation:
            print(f"  reconciliation: {reconciliation['status']} — {reconciliation['cycles']} "
                  f"cycles, {reconciliation['skipped']} skipped, "
                  f"{reconciliation['divergences_seen']} divergences seen")
        else:
            print(f"  reconciliation: {reconciliation.get('status', 'not_recorded')}")
        api = cert.get('api_calls') or {}
        if api.get('status') == 'recorded':
            print(f"  api: {api['calls']} calls, {api['errors']} errors, {api['slow_calls']} slow")
        # Every warning the file holds — the identity's, which fail it, and the analysis's, which
        # do not — is printed, or a FAILED would arrive here without its reason
        for warning in cert.get('warnings') or []:
            print(f'  ⚠️  {warning}')
        print(f'  certificate: {out_path}')
        print(f"{'=' * 60}\n")

    @staticmethod
    def _fee_source_text(fee_source: Dict[str, Any]) -> str:
        """
        The fee-source tally as the summary prints it after the fees.

        Args:
            fee_source: The certificate's fee-source block; empty on a certificate without one

        Returns:
            ' · venue 13/13 fills', ' · source not recorded', or '' where no fill was captured
        """
        status = fee_source.get('status')
        if status is None or status == 'no_fills':
            return ''
        if status == 'not_recorded':
            return ' · source not recorded'
        venue = fee_source['by_source'].get(FeeSource.VENUE.value, 0)
        text = f" · venue {venue}/{fee_source['fills']} fills"
        if fee_source['not_recorded']:
            text += f", {fee_source['not_recorded']} without a source"
        return text
